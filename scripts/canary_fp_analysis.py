#!/usr/bin/env python3
"""False-positive analysis for the contamination canary.

The threshold matters only if we know how often clean text trips it. The control
corpus here is real model output, not synthetic filler: every string was generated by
a model that never saw the canary token in its prompt. That is the population the
detector will actually run against when it screens a leaderboard submission.

    python scripts/canary_fp_analysis.py

Writes results/canary_fp.json and prints the numbers the paper quotes.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "harness"))
from agentfairbench import canary as C


def load_corpus():
    """Model-generated text produced without the canary anywhere in the prompt."""
    corpus, provenance = [], {}

    pub = ROOT / "data/profiles/public_dev.jsonl"
    rows = [json.loads(l) for l in pub.read_text(encoding="utf-8").splitlines() if l.strip()]
    texts = [r["content"] for r in rows] + [r["title"] for r in rows]
    corpus += texts
    provenance["public_split_profiles"] = len(texts)

    priv = ROOT / "data/private/private_test.jsonl"
    if priv.exists():
        rows = [json.loads(l) for l in priv.read_text(encoding="utf-8").splitlines() if l.strip()]
        # The stored records carry the canary as a field by design, so take only the
        # generated prose. Including the field would measure the detector against its
        # own token and tell us nothing about false positives.
        texts = [r["content"] for r in rows] + [r["title"] for r in rows]
        corpus += texts
        provenance["private_split_profiles"] = len(texts)

    for probe in sorted((ROOT / "results/name_probe").glob("*.jsonl")):
        rows = [json.loads(l) for l in probe.read_text(encoding="utf-8").splitlines() if l.strip()]
        texts = [json.dumps(r["rating"], ensure_ascii=False) for r in rows]
        corpus += texts
        provenance[f"name_probe_{probe.stem}"] = len(texts)

    return corpus, provenance


def main():
    corpus, provenance = load_corpus()
    fp = C.false_positive_rate(corpus, seed=20260612)
    chance = C.chance_probability(corpus_size=1e12)

    out = {
        "token": C.canary_string(),
        "fuzzy_threshold": C.FUZZY_THRESHOLD,
        "control_corpus": {
            "n_strings": len(corpus),
            "total_chars": sum(len(s) for s in corpus),
            "provenance": provenance,
            "description": (
                "Every string is model-generated output produced by prompts that never "
                "contained the canary token. This is the same population the detector "
                "screens when a leaderboard entry is submitted."),
        },
        "false_positive": fp,
        "chance_occurrence": chance,
    }
    dest = ROOT / "results" / "canary_fp.json"
    with open(dest, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=2)
        fh.write("\n")

    print(f"token            : {out['token']}")
    print(f"fuzzy threshold  : {out['fuzzy_threshold']}")
    print(f"control corpus   : {len(corpus)} strings, {out['control_corpus']['total_chars']} chars")
    print(f"  provenance     : {provenance}")
    for k, v in fp.items():
        print(f"  fp.{k:<22}: {v}")
    for k, v in chance.items():
        print(f"  chance.{k:<18}: {v}")
    print(f"\nwrote {dest}")


if __name__ == "__main__":
    main()
